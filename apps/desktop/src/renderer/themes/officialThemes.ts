export function registerOfficialThemes(): void {
  const { themes, register } = themeRegistryStore.getState();
  for (const theme of OFFICIAL_THEMES) {
    if (themes.some(t => t.id === theme.id)) continue;
    register(theme);
  }
}

registerOfficialThemes();
