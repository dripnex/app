#!/usr/bin/env node
/**
 * Reads drizzle/meta/_journal.json + drizzle/*.sql and writes
 * src/db/migrations.generated.ts for the Worker bundle.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8'));

const entries = journal.entries.map(entry => {
  const sql = readFileSync(join(root, 'drizzle', `${entry.tag}.sql`), 'utf8');
  return { id: entry.tag, idx: entry.idx, sql };
});

const body = `/* Generated by scripts/embed-migrations.mjs — do not edit. */
export type EmbeddedMigration = { id: string; idx: number; sql: string };

export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(entries, null, 2)};
`;

const out = join(root, 'src/db/migrations.generated.ts');
writeFileSync(out, body);
console.log(`wrote ${entries.length} migrations → src/db/migrations.generated.ts`);
